"""Generates the pixel "ki check mark" app icon (#18) as Android vector drawables and PNGs.

Usage: python3 tools/app-icon/generate_icon.py <repo root> <preview.png>  (needs Pillow)
"""
import math, sys, os
from PIL import Image, ImageDraw
REPO=sys.argv[1]; RES=f'{REPO}/androidApp/src/main/res'
CHECK=["...........###","..........####",".........####.","........####..","###....####...",
       "####..####....",".#######......","..#####.......","...###........"]
CELL=4; OX=54-len(CHECK[0])*CELL/2; OY=54-len(CHECK)*CELL/2
KI='FF9A3C'; SHADOW='B8551A'; CORE='FFF3DF'; TOP='2B2F55'; BOTTOM='22264A'
def cells(): return [(x,y) for y,r in enumerate(CHECK) for x,c in enumerate(r) if c=='#']
def core_cells(): return [(x,y) for x,y in cells() if 0<x<len(CHECK[0])-1 and CHECK[y][x-1]=='#' and CHECK[y][x+1]=='#']
def glow_layers(cx=54,cy=54,r=30,g=4,start=2):
    out={170:[],110:[],60:[]}
    for gy in range(start,108,g):
        for gx in range(start,108,g):
            d=math.hypot(gx+g/2-cx,gy+g/2-cy)/r
            if d<=1: out[60 if d>0.8 else (110 if d>0.6 else 170)].append((gx,gy,g,g))
    return [(a,rs) for a,rs in sorted(out.items()) if rs]
def mark_rects(scale=1.0, ox=OX, oy=OY, cell=CELL):
    c=cell*scale; sh=c*0.25
    shadow=[(ox+x*c+sh,oy+y*c+sh,c,c) for x,y in cells()]
    main=[(ox+x*c,oy+y*c,c,c) for x,y in cells()]
    core=[(ox+x*c+c*0.3,oy+y*c+c*0.3,c*0.4,c*0.4) for x,y in core_cells()]
    return shadow,main,core
# --- shapes: list of (argb hex 8, rects)
def foreground():
    sh,m,co=mark_rects()
    return [(f'{a:02X}{KI}',rs) for a,rs in glow_layers()]+[('FF'+SHADOW,sh),('FF'+KI,m),('FF'+CORE,co)]
def background(): return [('FF'+TOP,[(0,0,108,54)]),('FF'+BOTTOM,[(0,54,108,54)])]
def monochrome(): return [('FF000000',mark_rects()[1])]
def fmt(v): s=f'{v:.2f}'.rstrip('0').rstrip('.'); return s
def path(rects): return ''.join(f'M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z' for x,y,w,h in rects)
def vector(shapes, comment, size=108, vp=108, clip=None):
    lines=['<?xml version="1.0" encoding="utf-8"?>',f'<!-- {comment} -->',
      '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
      f'    android:width="{size}dp"',f'    android:height="{size}dp"',
      f'    android:viewportWidth="{vp}"',f'    android:viewportHeight="{vp}">']
    for col,rs in shapes: lines.append(f'    <path android:fillColor="#{col}" android:pathData="{path(rs)}" />')
    lines.append('</vector>'); return '\n'.join(lines)+'\n'
def render(shapes, px, vp=108):
    U=px/vp; im=Image.new('RGBA',(px,px))
    for col,rs in shapes:
        a=int(col[:2],16); rgb=tuple(int(col[i:i+2],16) for i in (2,4,6))
        layer=Image.new('RGBA',(px,px)); d=ImageDraw.Draw(layer)
        for x,y,w,h in rs: d.rectangle([round(x*U),round(y*U),round((x+w)*U)-1,round((y+h)*U)-1],fill=rgb+(a,))
        im.alpha_composite(layer)
    return im
def masked(im, shape, out):
    s=im.size[0]; a,b=round(s/6),round(s*5/6)
    m=Image.new('L',(s,s)); d=ImageDraw.Draw(m)
    (d.ellipse if shape=='circle' else (lambda bb,fill: d.rounded_rectangle(bb,radius=round(s*0.15),fill=fill)))([a,a,b-1,b-1],fill=255)
    o=Image.new('RGBA',(s,s)); o.paste(im,(0,0),m); return o.crop((a,a,b,b)).resize((out,out),Image.LANCZOS)
D=f'{RES}/drawable'
open(f'{D}/ki_check_launcher_background.xml','w').write(vector(background(),'Ki check mark app icon (#18): dark arena blue in two bands. Generated by tools/app-icon/generate_icon.py.'))
open(f'{D}/ki_check_launcher_foreground.xml','w').write(vector(foreground(),'Ki check mark app icon (#18): a pixel check mark of orange ki with a dark edge and bright core dots in a stepped ki glow.'))
open(f'{D}/ki_check_launcher_monochrome.xml','w').write(vector(monochrome(),'Ki check mark app icon (#18), themed icon: the pixel check mark alone.'))
# splash: disc of navy (stepped) + glow + mark, inside the 72 unit circle
disc=[(x,y,4,4) for y in range(18,90,4) for x in range(18,90,4) if math.hypot(x+2-54,y+2-54)<=36]
splash=[('FF'+TOP,[r for r in disc if r[1]<54]),('FF'+BOTTOM,[r for r in disc if r[1]>=54])]+foreground()
open(f'{D}/ki_check_splash_icon.xml','w').write(vector(splash,'Splash icon (#18): the ki check mark on a round arena blue disc.'))
# 24dp white glyphs
c24=1.4; sw=len(CHECK[0])*c24; shh=len(CHECK)*c24
glyph=[('FFFFFFFF',mark_rects(1,12-sw/2,12-shh/2+0.4,c24)[1])]
open(f'{D}/notif_icon.xml','w').write(vector(glyph,'Notification icon (#18): the pixel ki check mark.',24,24))
open(f'{REPO}/shared/ui/src/commonMain/composeResources/drawable/ki_check_icon.xml','w').write(vector(glyph,'App logo (#18): the pixel ki check mark, tinted by the caller.',24,24))
# PNG fallbacks
full_bg=render(background(),864); fg=render(foreground(),864); full=full_bg.copy(); full.alpha_composite(fg)
for dname,mult in [('mdpi',1),('hdpi',1.5),('xhdpi',2),('xxhdpi',3),('xxxhdpi',4)]:
    md=f'{RES}/mipmap-{dname}'; n=round(108*mult)
    render(background(),n).save(f'{md}/ic_launcher_background.png')
    render(foreground(),n).save(f'{md}/ic_launcher_foreground.png')
    render(monochrome(),n).save(f'{md}/ic_launcher_monochrome.png')
    masked(full,'squircle',round(48*mult)).save(f'{md}/ic_launcher.png')
masked(full,'circle',512).save(f'{REPO}/fastlane/metadata/android/en-US/images/icon.png')
# preview sheet
sheet=Image.new('RGBA',(900,300),(245,243,238,255))
sheet.alpha_composite(masked(full,'circle',256),(20,22)); sheet.alpha_composite(masked(full,'squircle',256),(296,22))
mono=Image.new('RGBA',(864,864),(225,230,240,255)); mono.alpha_composite(render([('FF3A4A6A',monochrome()[0][1])],864))
sheet.alpha_composite(masked(mono,'circle',128),(572,22)); sheet.alpha_composite(masked(full,'circle',96),(572,170)); sheet.alpha_composite(masked(full,'circle',48),(690,194))
sp=render(splash,256); sheet.alpha_composite(sp.crop((40,40,216,216)).resize((128,128),Image.LANCZOS),(740,22))
sheet.save(sys.argv[2]); print('ok')
